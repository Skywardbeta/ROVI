#!/usr/bin/env bash
# Generates the thirty-arm world, bridge, parameters, and launch file from one workcell layout.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
world="$repo_root/src/rovi_sim/worlds/thirty_arms.sdf"
bridge="$repo_root/src/rovi_sim/config/thirty_arms_bridge.yaml"
params="$repo_root/src/rovi_bringup/config/thirty_arms.yaml"
launch="$repo_root/src/rovi_bringup/launch/thirty_arms.launch.xml"

workcells=10
team=3
columns=5
cell_dx=3.0
cell_dy=4.5
arm_spacing=1.0
skew_ns=80000000
notice="Generated by scripts/generate_thirty_arms.sh; edit the script and regenerate, not this file."
goals='[0.0, -0.499, 0.0, -2.382, 0.0, 1.883, 0.785,
                -0.168, 0.275, -0.365, -1.798, 0.11, 2.054, 0.714,
                0.054, 0.542, -0.596, -1.907, 0.409, 2.326, 0.523,
                -0.168, 0.275, -0.365, -1.798, 0.11, 2.054, 0.714,
                0.168, 0.275, 0.365, -1.798, -0.11, 2.054, 0.857,
                -0.054, 0.542, 0.596, -1.907, -0.409, 2.326, 1.048,
                0.168, 0.275, 0.365, -1.798, -0.11, 2.054, 0.857]'
colours=("0.85 0.15 0.15" "0.15 0.65 0.2" "0.15 0.3 0.85" "0.9 0.75 0.1" "0.6 0.2 0.75")

calc() { awk "BEGIN { printf \"%.3f\", $1 }"; }

robot_name() { printf 'robot_%02d' "$1"; }

visual_box() {
  local name="$1" x="$2" y="$3" z="$4" size="$5" rgb="$6"
  cat <<EOF
    <model name="$name">
      <static>true</static>
      <pose>$x $y $z 0 0 0</pose>
      <link name="link">
        <visual name="visual">
          <geometry>
            <box>
              <size>$size</size>
            </box>
          </geometry>
          <material>
            <ambient>$rgb 1</ambient>
            <diffuse>$rgb 1</diffuse>
          </material>
        </visual>
      </link>
    </model>
EOF
}

write_world() {
  cat <<EOF
<?xml version="1.0"?>
<!-- $notice -->
<sdf version="1.9">
  <world name="thirty_arms">
    <physics name="2ms" type="ignored">
      <max_step_size>0.002</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 10 0 0 0</pose>
      <diffuse>0.85 0.85 0.85 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.4 0.2 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision">
          <geometry>
            <plane>
              <normal>0 0 1</normal>
              <size>40 40</size>
            </plane>
          </geometry>
        </collision>
        <visual name="visual">
          <geometry>
            <plane>
              <normal>0 0 1</normal>
              <size>40 40</size>
            </plane>
          </geometry>
          <material>
            <ambient>0.8 0.8 0.8 1</ambient>
            <diffuse>0.8 0.8 0.8 1</diffuse>
          </material>
        </visual>
      </link>
    </model>
EOF
  visual_box access_point "$(calc "2 * $cell_dx + 0.35")" "$(calc "$cell_dy - 1.25")" 1.0 \
    "0.08 0.08 2.0" "0.9 0.5 0.1"
  local cell arm robot x0 y0 y
  for ((cell = 0; cell < workcells; ++cell)); do
    x0="$(calc "($cell % $columns) * $cell_dx")"
    y0="$(calc "int($cell / $columns) * $cell_dy")"
    visual_box "table_$cell" "$(calc "$x0 + 0.35")" "$(calc "$y0 + $arm_spacing")" 0.375 \
      "1.4 3.2 0.75" "0.55 0.4 0.25"
    for ((arm = 0; arm < team; ++arm)); do
      robot=$((cell * team + arm))
      y="$(calc "$y0 + $arm * $arm_spacing")"
      visual_box "pick_tray_$robot" "$(calc "$x0 + 0.55")" "$(calc "$y - 0.3")" 0.76 \
        "0.3 0.2 0.02" "0.2 0.2 0.25"
      visual_box "place_tray_$robot" "$(calc "$x0 + 0.55")" "$(calc "$y + 0.3")" 0.76 \
        "0.3 0.2 0.02" "0.2 0.2 0.25"
      visual_box "block_$robot" "$(calc "$x0 + 0.55")" "$(calc "$y - 0.3")" 0.795 \
        "0.05 0.05 0.05" "${colours[$((cell % ${#colours[@]}))]}"
      cat <<EOF
    <include>
      <uri>model://rovi_panda_fuel_v5</uri>
      <name>panda_$(printf '%02d' "$robot")</name>
      <pose>$x0 $y 0.75 0 0 0</pose>
      <plugin filename="gz-sim-joint-state-publisher-system" name="gz::sim::systems::JointStatePublisher">
        <update_rate>25</update_rate>
      </plugin>
    </include>
EOF
    done
  done
  cat <<EOF
  </world>
</sdf>
EOF
}

write_bridge() {
  cat <<EOF
# $notice
- ros_topic_name: /clock
  gz_topic_name: /clock
  ros_type_name: rosgraph_msgs/msg/Clock
  gz_type_name: gz.msgs.Clock
  direction: GZ_TO_ROS
EOF
  local robot joint panda
  for ((robot = 0; robot < workcells * team; ++robot)); do
    panda="panda_$(printf '%02d' "$robot")"
    cat <<EOF
- ros_topic_name: /$(robot_name "$robot")/joint_states
  gz_topic_name: /world/thirty_arms/model/$panda/joint_state
  ros_type_name: sensor_msgs/msg/JointState
  gz_type_name: gz.msgs.Model
  direction: GZ_TO_ROS
EOF
    for ((joint = 1; joint <= 7; ++joint)); do
      cat <<EOF
- ros_topic_name: /$(robot_name "$robot")/arm/panda_joint$joint/position
  gz_topic_name: /model/$panda/joint/panda_joint$joint/0/cmd_pos
  ros_type_name: std_msgs/msg/Float64
  gz_type_name: gz.msgs.Double
  direction: ROS_TO_GZ
EOF
    done
  done
}

write_params() {
  cat <<EOF
# $notice
# Thirty-arm scenario: ten workcells of three Pandas share one access point and three workers.
# Every value is a controlled synthetic input (docs/network-service-model.md), not a measured deployment.
# The handover outage is time-indexed from the scheduler epoch. Times are integer nanoseconds, rates are
# bits per second, sizes are bytes, angles are radians. Workcells 0-4 use model class 1, 5-9 class 2.

/rovi_scheduler:
  ros__parameters:
    policy: least_slack
    cycle_period_ns: 10000000
    release_tolerance_ns: 50000000
    slot_length_ns: 1000000
    horizon_slots: 2000
    max_pending_jobs: 256
    uplink:
      first_slots: [0, 6000, 7500]
      rates_bps: [100000000, 0, 80000000]
      reductions_permille: [100, 100, 100]
    downlink:
      first_slots: [0, 6000, 7500]
      rates_bps: [50000000, 0, 40000000]
      reductions_permille: [100, 100, 100]
    medium:
      enabled: false
    uplink_delay_ns: 2000000
    downlink_delay_ns: 2000000
    # Planned gap before each dispatched stage. Free-running runs saw sends reach the link up to 28 ms
    # after their stage was ready (48 ms during startup); 35 ms is not a guarantee.
    dispatch_lead_ns: 35000000
    workers:
      ids: [1, 1, 2, 3]
      model_classes: [1, 2, 1, 2]
      durations_ns: [15000000, 30000000, 15000000, 30000000]
    run:
      id: thirty_arms
      seed: 0
      network_profile_id: synthetic-edge-handover-v1

/rovi_link:
  ros__parameters:
    poll_period_ns: 1000000
    orphan_timeout_ns: 1000000000
    max_lead_ns: 2000000000

/rovi_worker_1:
  ros__parameters:
    worker_id: 1
    model_classes: [1, 2]
    durations_ns: [15000000, 30000000]
    slowdown_ns: 0
    poll_period_ns: 1000000
    orphan_timeout_ns: 1000000000
    max_lead_ns: 2000000000

/rovi_worker_2:
  ros__parameters:
    worker_id: 2
    model_classes: [1]
    durations_ns: [15000000]
    slowdown_ns: 0
    poll_period_ns: 1000000
    orphan_timeout_ns: 1000000000
    max_lead_ns: 2000000000

/rovi_worker_3:
  ros__parameters:
    worker_id: 3
    model_classes: [2]
    durations_ns: [30000000]
    slowdown_ns: 0
    poll_period_ns: 1000000
    orphan_timeout_ns: 1000000000
    max_lead_ns: 2000000000

/rovi_coordinator:
  ros__parameters:
    workcells: $workcells
    robots_per_workcell: $team
    maximum_result_ready_skew_ns: $skew_ns
    expiry_period_ns: 10000000
    expiry_grace_ns: 50000000
    max_tracked_groups: 64
EOF
  local robot cell model workers
  for ((robot = 0; robot < workcells * team; ++robot)); do
    cell=$((robot / team))
    if ((cell < workcells / 2)); then model=1 workers="[1, 2]"; else model=2 workers="[1, 3]"; fi
    cat <<EOF

/$(robot_name "$robot")/robot_agent:
  ros__parameters:
    robot_id: $robot
    grouped: true
    release_grace_ns: 100000000
    observation_period_ns: 100000000
    state_period_ns: 100000000
    initial_buffer_ns: 600000000
    chunk_horizon_ns: 600000000
    maximum_buffer_ns: 1000000000
    safety_margin_ns: 50000000
    maximum_result_age_ns: 600000000
    upload_bytes: $((60000 + 8000 * cell))
    action_chunk_bytes: 20000
    model_class: $model
    eligible_workers: $workers

/$(robot_name "$robot")/arm_controller:
  ros__parameters:
    robot_id: $robot
    control_period_ns: 40000000
    progress_period_ns: 500000000
    state_timeout_ns: 300000000
    feedback_timeout_ns: 300000000
    joint_names: [panda_joint1, panda_joint2, panda_joint3, panda_joint4, panda_joint5,
                  panda_joint6, panda_joint7]
    goals_rad: $goals
    joint_lower_rad: [-2.8972, -1.7628, -2.8972, -3.0718, -2.8972, -0.0175, -2.8972]
    joint_upper_rad: [2.8972, 1.7628, 2.8972, -0.0698, 2.8972, 3.7525, 2.8972]
    max_joint_speed_rps: 0.6
    tolerance_rad: 0.1
    settle_time_ns: 1000000000
EOF
  done
}

composable() {
  local plugin="$1" name="$2" space="$3"
  cat <<EOF
    <composable_node pkg="$4" plugin="$plugin" name="$name" namespace="$space">
      <param from="\$(var params_file)"/>
      <param name="use_sim_time" value="true"/>
    </composable_node>
EOF
}

write_launch() {
  cat <<EOF
<launch>
  <!-- $notice -->
  <arg name="record" default="false"/>
  <arg name="bag_uri" default="rovi_bags/thirty_arms"/>
  <arg name="foxglove" default="true"/>
  <arg name="foxglove_port" default="8765"/>
  <arg name="gui" default="false"/>
  <arg name="git_revision" default="\$(env ROVI_GIT_REVISION unknown)"/>
  <arg name="params_file" default="\$(find-pkg-share rovi_bringup)/config/thirty_arms.yaml"/>
  <arg name="world" default="\$(find-pkg-share rovi_sim)/worlds/thirty_arms.sdf"/>
  <arg name="bridge_config" default="\$(find-pkg-share rovi_sim)/config/thirty_arms_bridge.yaml"/>

  <set_env name="GZ_IP" value="127.0.0.1"/>

  <node_container pkg="rclcpp_components" exec="component_container_mt" name="rovi_container" namespace="/">
    <composable_node pkg="ros_gz_sim" plugin="ros_gz_sim::GzServer" name="gz_server" namespace="/">
      <param name="world_sdf_file" value="\$(var world)"/>
    </composable_node>
    <composable_node pkg="ros_gz_bridge" plugin="ros_gz_bridge::RosGzBridge" name="gz_bridge" namespace="/">
      <param name="config_file" value="\$(var bridge_config)"/>
    </composable_node>
    <composable_node pkg="rovi_scheduler" plugin="rovi::scheduler::SchedulerNode" name="rovi_scheduler" namespace="/">
      <param from="\$(var params_file)"/>
      <param name="use_sim_time" value="true"/>
      <param name="run.git_revision" value="\$(var git_revision)"/>
    </composable_node>
EOF
  composable rovi::network::LinkNode rovi_link / rovi_network
  composable rovi::worker::WorkerNode rovi_worker_1 / rovi_worker
  composable rovi::worker::WorkerNode rovi_worker_2 / rovi_worker
  composable rovi::worker::WorkerNode rovi_worker_3 / rovi_worker
  composable rovi::coordination::CoordinatorNode rovi_coordinator / rovi_coordination
  local robot
  for ((robot = 0; robot < workcells * team; ++robot)); do
    composable rovi::robot_agent::RobotAgentNode robot_agent "/$(robot_name "$robot")" rovi_robot_agent
    composable rovi::robot_agent::ArmControllerNode arm_controller "/$(robot_name "$robot")" rovi_robot_agent
  done
  cat <<EOF
    <composable_node pkg="rosbag2_transport" plugin="rosbag2_transport::Recorder" name="rovi_recorder" namespace="/" if="\$(var record)">
      <param name="use_sim_time" value="true"/>
      <param name="storage.uri" value="\$(var bag_uri)"/>
      <param name="storage.storage_id" value="mcap"/>
      <param name="record.all_topics" value="false"/>
      <param name="record.regex" value="^/rovi/|^/robot_[0-9]{2}/joint_states\$"/>
      <param name="record.disable_keyboard_controls" value="true"/>
    </composable_node>
  </node_container>

  <node pkg="foxglove_bridge" exec="foxglove_bridge" name="foxglove_bridge" namespace="/" if="\$(var foxglove)">
    <param name="use_sim_time" value="true"/>
    <param name="address" value="127.0.0.1"/>
    <param name="port" value="\$(var foxglove_port)"/>
    <param name="capabilities" value="[connectionGraph]"/>
    <param name="topic_whitelist" value="['^/rovi/.*', '^/robot_[0-9]{2}/joint_states\$', '^/clock\$']"/>
    <param name="param_whitelist" value="['(?!)']"/>
    <param name="service_whitelist" value="['(?!)']"/>
    <param name="client_topic_whitelist" value="['(?!)']"/>
    <param name="asset_uri_allowlist" value="['(?!)']"/>
    <param name="sysinfo" value="false"/>
    <param name="remote_access" value="false"/>
  </node>

  <executable cmd="gz sim -g" if="\$(var gui)">
    <env name="QT_QPA_PLATFORM" value="xcb"/>
  </executable>
</launch>
EOF
}

check=false
if [[ $# -eq 1 && "$1" == "--check" ]]; then
  check=true
elif [[ $# -ne 0 ]]; then
  echo "usage: $0 [--check]" >&2
  exit 2
fi

stage="$(mktemp -d)"
trap 'rm -rf -- "$stage"' EXIT
write_world > "$stage/world"
write_bridge > "$stage/bridge"
write_params > "$stage/params"
write_launch > "$stage/launch"
status=0
for pair in "world:$world" "bridge:$bridge" "params:$params" "launch:$launch"; do
  generated="$stage/${pair%%:*}"
  target="${pair#*:}"
  if $check; then
    if ! cmp -s -- "$generated" "$target"; then
      echo "$target differs from the generator; run $0 and commit the result" >&2
      status=1
    fi
  else
    mv -f -- "$generated" "$target"
  fi
done
if $check; then
  exit "$status"
fi
echo "generated $world, $bridge, $params, and $launch"
